_FILES = {"schema": SCHEMA_FILES, "migrations": MIGRATION_FILES, "app": APP_FILES}
_COMMENT = re.compile(r"^\s*(--|#)")


def _code_lines(text: str) -> list[str]:
    """Python source without docstrings and bare string statements: prose that mentions
    BEGIN IMMEDIATE is not code that depends on it."""
    lines = text.splitlines()
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return lines
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            for number in range(node.lineno - 1, (node.end_lineno or node.lineno)):
                lines[number] = ""
    return lines


def scan() -> dict:
    counts: dict[str, int] = {}
    sites: dict[str, list[str]] = defaultdict(list)
    for pattern in PATTERNS:
        rx = re.compile(pattern.regex, re.IGNORECASE if pattern.where == "schema" else 0)
        total = 0
        for path in _FILES[pattern.where]:
            if not path.exists():
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            if pattern.where == "schema":
                text = "\n".join("" if _COMMENT.match(line) else line for line in text.splitlines())
                hits = len(rx.findall(text))
            else:
                hits = sum(
                    1 for line in _code_lines(text) if rx.search(line) and not _COMMENT.match(line)
                )
            if hits:
                total += hits
                sites[pattern.key].append(f"{path.relative_to(REPO).as_posix()} ({hits})")
        counts[pattern.key] = total
    return {"counts": counts, "sites": dict(sites)}


def render(result: dict, baseline: dict | None) -> str:
    lines = [f"{'Construct':<52} {'Sev.':<8} {'Now':>5} {'Base':>5}", "-" * 74]
    for pattern in PATTERNS:
        now = result["counts"][pattern.key]
        base = "" if baseline is None else str(baseline.get(pattern.key, "new"))
        lines.append(f"{pattern.description:<52} {pattern.severity:<8} {now:>5} {base:>5}")
    by_severity: dict[str, int] = defaultdict(int)
    for pattern in PATTERNS:
        by_severity[pattern.severity] += result["counts"][pattern.key]
    lines.append("-" * 74)
    lines.append(
        "Totals: " + ", ".join(f"{k} {by_severity[k]}" for k in ("BLOCKER", "PORT", "NOTE"))
    )
    return "\n".join(lines)


def check(result: dict) -> list[str]:
    if not BASELINE.exists():
        return [f"{BASELINE.name} is missing; run with --update-baseline once."]
    baseline = json.loads(BASELINE.read_text(encoding="utf-8"))["counts"]
    problems = []
    for pattern in PATTERNS:
        now, allowed = result["counts"][pattern.key], baseline.get(pattern.key)
        if allowed is None:
            problems.append(f"{pattern.key}: new construct class, not in the baseline")
        elif now > allowed:
            where = "; ".join(result["sites"].get(pattern.key, []))
            problems.append(
                f"{pattern.key}: {now} > baseline {allowed} - {pattern.description}. "
                f"Port note: {pattern.port} Sites: {where}"
            )
        elif now < allowed:
            problems.append(
                f"{pattern.key}: {now} < baseline {allowed} - progress; lower the baseline with "
                "--update-baseline so it cannot grow back"
            )
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--update-baseline", action="store_true")
    parser.add_argument("--json", metavar="FILE")
    args = parser.parse_args(argv)

    result = scan()
    baseline = (
        json.loads(BASELINE.read_text(encoding="utf-8"))["counts"] if BASELINE.exists() else None
    )
    print(render(result, baseline))

    if args.json:
        Path(args.json).write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    if args.update_baseline:
        BASELINE.write_text(
            json.dumps(
                {
                    "note": "SQLite-specific construct counts; see scripts/pg_readiness.py",
                    "counts": result["counts"],
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
        print(f"Baseline written to {BASELINE.name}")
        return 0
    if args.check:
        problems = check(result)
        for problem in problems:
            print("RATCHET:", problem, file=sys.stderr)
        return 1 if problems else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
